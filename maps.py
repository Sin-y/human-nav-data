import random
import numpy as np


def build_map_from_layout(layout):
    height, width = len(layout), len(layout[0])
    grid = np.zeros((height, width), dtype=np.int32)
    start = goal = None
    for r_idx, row in enumerate(reversed(layout)):
        for c_idx, ch in enumerate(row):
            grid[r_idx, c_idx] = 1 if ch == "#" else 0
            if ch == "S":
                start = np.array([c_idx + 0.5, r_idx + 0.5], dtype=np.float32)
            elif ch == "G":
                goal = np.array([c_idx + 0.5, r_idx + 0.5], dtype=np.float32)
    return grid, start, goal


def random_map_name(rng=None, exclude_maze=False):
    rng = rng or random
    names = list(MAPS.keys())
    if exclude_maze:
        names = [n for n in names if n != "maze_supplementary"]
    return rng.choice(names)
